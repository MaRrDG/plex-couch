"""Generate static/tokens.css from docs/design-system/tokens.json.

    python tools/build_tokens.py [--check]

Writes one CSS custom property per token (`--bg`, `--space-4`, `--radius-lg`, ...) and one
class per type style (`.title-screen`, `.data`, ...). With --check it only compares the file
on disk with what would be generated and exits 1 if they differ.
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS = os.path.join(ROOT, "docs", "design-system", "tokens.json")
OUT = os.path.join(ROOT, "static", "tokens.css")
THEME = "dark"

HEADER = ("/* Generated by tools/build_tokens.py from docs/design-system/tokens.json.\n"
          "   Do not edit by hand: change tokens.json and run the script again. */\n")


def _color(value):
    return value[THEME] if isinstance(value, dict) else value


def render(tokens):
    """Return the CSS text for a parsed tokens.json."""
    props = []
    for t in tokens["color"]["tokens"]:
        props.append(("--%s" % t["name"], _color(t["value"])))
    for name, stack in tokens["type"]["families"].items():
        props.append(("--font-%s" % name, stack))
    for group in ("spacing", "radius", "shadow", "size"):
        for t in tokens[group]["tokens"]:
            props.append(("--%s" % t["name"], t["value"]))

    lines = [HEADER, ":root {"]
    lines += ["  %s: %s;" % (k, v) for k, v in props]
    lines.append("}")

    for group in tokens["type"]["groups"]:
        family = group.get("family", "sans")
        for s in group["styles"]:
            decl = [
                ("font-family", "var(--font-%s)" % family),
                ("font-size", s["fontSize"]),
                ("line-height", s["lineHeight"]),
                ("font-weight", str(s["fontWeight"])),
            ]
            if s.get("letterSpacing"):
                decl.append(("letter-spacing", s["letterSpacing"]))
            if "tabular" in (s.get("usage") or "").lower():
                decl.append(("font-variant-numeric", "tabular-nums"))
            lines.append("")
            lines.append(".%s {" % s["name"])
            lines += ["  %s: %s;" % (k, v) for k, v in decl]
            lines.append("}")
    return "\n".join(lines) + "\n"


def load(path=TOKENS):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="only verify static/tokens.css is up to date")
    args = p.parse_args(argv)
    css = render(load())
    if args.check:
        try:
            with open(OUT, "r", encoding="utf-8") as f:  # universal newlines: CRLF checkouts pass
                current = f.read()
        except OSError:
            current = None
        if current != css:
            print("static/tokens.css is out of date; run tools/build_tokens.py")
            return 1
        print("static/tokens.css is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(css)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
