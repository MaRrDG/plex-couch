//! `static/tokens.css` from `docs/design-system/tokens.json`: one CSS custom property per
//! token (`--bg`, `--space-4`, `--radius-lg`, ...) and one class per type style
//! (`.title-screen`, `.data`, ...). Colours use the dark theme. Written by
//! `cargo run --example build_tokens`; a test checks the file on disk is up to date.

use crate::json::{py_str, truthy};
use serde_json::Value;

/// The design-system tokens, relative to the repository root.
pub const TOKENS_JSON: &str = "docs/design-system/tokens.json";
/// The generated stylesheet, relative to the repository root.
pub const TOKENS_CSS: &str = "static/tokens.css";
const THEME: &str = "dark";

pub const HEADER: &str = "/* Generated by `cargo run --example build_tokens` from docs/design-system/tokens.json.\n   \
Do not edit by hand: change tokens.json and run the example again. */\n";

fn arr(v: &Value) -> &[Value] {
    v.as_array().map(Vec::as_slice).unwrap_or(&[])
}

fn name(v: &Value) -> String {
    py_str(&v["name"])
}

/// The CSS text for a parsed `tokens.json`.
pub fn render(tokens: &Value) -> String {
    let mut props: Vec<(String, String)> = Vec::new();
    for t in arr(&tokens["color"]["tokens"]) {
        let v = &t["value"];
        let val = if v.is_object() { py_str(&v[THEME]) } else { py_str(v) };
        props.push((format!("--{}", name(t)), val));
    }
    if let Some(families) = tokens["type"]["families"].as_object() {
        for (family, stack) in families {
            props.push((format!("--font-{family}"), py_str(stack)));
        }
    }
    for group in ["spacing", "radius", "shadow", "size"] {
        for t in arr(&tokens[group]["tokens"]) {
            props.push((format!("--{}", name(t)), py_str(&t["value"])));
        }
    }

    let mut lines: Vec<String> = vec![HEADER.to_string(), ":root {".to_string()];
    lines.extend(props.iter().map(|(k, v)| format!("  {k}: {v};")));
    lines.push("}".into());

    for group in arr(&tokens["type"]["groups"]) {
        let family = group.get("family").and_then(Value::as_str).unwrap_or("sans");
        for s in arr(&group["styles"]) {
            let mut decl = vec![
                ("font-family".to_string(), format!("var(--font-{family})")),
                ("font-size".to_string(), py_str(&s["fontSize"])),
                ("line-height".to_string(), py_str(&s["lineHeight"])),
                ("font-weight".to_string(), py_str(&s["fontWeight"])),
            ];
            if truthy(s.get("letterSpacing")) {
                decl.push(("letter-spacing".into(), py_str(&s["letterSpacing"])));
            }
            if s.get("usage").and_then(Value::as_str).unwrap_or("").to_lowercase().contains("tabular") {
                decl.push(("font-variant-numeric".into(), "tabular-nums".into()));
            }
            lines.push(String::new());
            lines.push(format!(".{} {{", name(s)));
            lines.extend(decl.iter().map(|(k, v)| format!("  {k}: {v};")));
            lines.push("}".into());
        }
    }
    lines.join("\n") + "\n"
}
